/**
 * @maataa/ui/navigation/AppShell
 * Responsive application frame for workspace navigation and page content.
 */

import React, { useEffect, useId, useRef, useState } from "react";
import { colorTokens } from "../tokens";
import { Sidebar, type SidebarProps } from "./Sidebar";

export type AppShellNavigationPosition = "left" | "right" | "top" | "folded";
export type AppShellRegionPosition = "above" | "below";

export interface AppShellProps {
  /** Top-level brand and actions, spanning the full application frame. */
  topNav?: React.ReactNode;
  /** Navigation rail. A `Sidebar` receives the selected orientation and collapsed state. */
  sidebar?: React.ReactNode;
  /** Page-level tools, such as filters or create actions. */
  toolbar?: React.ReactNode;
  /** Persistent application footer. */
  footer?: React.ReactNode;
  /** Main page content. */
  children: React.ReactNode;
  /** Whether the frame fills the viewport height. @default true */
  fullHeight?: boolean;
  /** Navigation placement and initial density. @default "left" */
  navigationPosition?: AppShellNavigationPosition;
  /** Initial desktop collapsed state. Folded placement always starts collapsed. */
  navigationCollapsed?: boolean;
  /** Show a desktop control for folding and unfolding navigation. @default true */
  collapsible?: boolean;
  /** Position the toolbar relative to page content. @default "above" */
  toolbarPosition?: AppShellRegionPosition;
  /** Position the footer relative to page content. @default "below" */
  footerPosition?: AppShellRegionPosition;
  /** Accessible label for the navigation controls. @default "Primary navigation" */
  navigationLabel?: string;
  /** Optional id for the main landmark. A unique id is generated by default. */
  mainId?: string;
  /** Additional class for the outer frame. */
  className?: string;
  /** Additional styles for the outer frame. */
  style?: React.CSSProperties;
}

