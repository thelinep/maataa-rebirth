function MenuGlyph() {
  return (
    <svg
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth="1.8"
      strokeLinecap="round"
      aria-hidden="true"
    >
      <path d="M4 6.5h16M4 12h16M4 17.5h16" />
    </svg>
  );
}

/**
 * Responsive shell that composes navigation, global actions, page tools,
 * content, and persistent footer regions. Existing `topNav`, `sidebar`, and
 * `children` composition remains supported.
 */
export const AppShell: React.FC<AppShellProps> = ({
  topNav,
  sidebar,
  toolbar,
  footer,
  children,
  fullHeight = true,
  navigationPosition = "left",
  navigationCollapsed = false,
  collapsible = true,
  toolbarPosition = "above",
  footerPosition = "below",
  navigationLabel = "Primary navigation",
  mainId,
  className,
  style,
}) => {
  const generatedId = useId();
  const navigationId = `maataa-navigation-${generatedId.replace(/:/g, "")}`;
  const contentId = mainId ?? `maataa-main-${generatedId.replace(/:/g, "")}`;
  const [collapsed, setCollapsed] = useState(
    navigationPosition === "folded" || navigationCollapsed
  );
  const [mobileOpen, setMobileOpen] = useState(false);
  const mobileToggleRef = useRef<HTMLButtonElement>(null);

  useEffect(() => {
    if (!mobileOpen) return undefined;
    const onKeyDown = (event: KeyboardEvent) => {
      if (event.key === "Escape") {
        setMobileOpen(false);
        mobileToggleRef.current?.focus();
      }
    };
    document.addEventListener("keydown", onKeyDown);
    return () => document.removeEventListener("keydown", onKeyDown);
  }, [mobileOpen]);

  const orientation = navigationPosition === "top" ? "horizontal" : "vertical";
  const navigationContent =
    React.isValidElement<SidebarProps>(sidebar) && sidebar.type === Sidebar
      ? React.cloneElement(sidebar, {
          collapsed: orientation === "horizontal" ? false : collapsed && !mobileOpen,
          orientation,
          label: navigationLabel,
          ...(orientation === "horizontal" ? { width: "100%" } : {}),
        })
      : sidebar;
  const shellClassName = ["maataa-app-shell", className].filter(Boolean).join(" ");
  const shellStyle: React.CSSProperties = {
    height: fullHeight ? "100vh" : "100%",
    backgroundColor: colorTokens.background.secondary,
    ...style,
  };
  const toggle = (kind: "mobile" | "desktop") => (
    <button
      ref={kind === "mobile" ? mobileToggleRef : undefined}
      type="button"
      className={`maataa-app-shell__toggle maataa-app-shell__${kind}-toggle`}
      aria-label={
        kind === "mobile"
          ? mobileOpen
            ? "Close navigation"
            : "Open navigation"
          : collapsed
            ? "Expand navigation"
            : "Collapse navigation"
      }
      aria-controls={navigationId}
      aria-expanded={kind === "mobile" ? mobileOpen : !collapsed}
      onClick={() =>
        kind === "mobile" ? setMobileOpen((open) => !open) : setCollapsed((value) => !value)
      }
    >
      <MenuGlyph />
    </button>
  );

  return (
    <div
      className={shellClassName}
      style={shellStyle}
      data-navigation-position={navigationPosition}
      data-full-height={fullHeight}
    >
      <style>{shellStyles}</style>
      <a className="maataa-app-shell__skip" href={`#${contentId}`}>
        Skip to content
      </a>
      {(topNav || sidebar) && (
        <div className="maataa-app-shell__top">
          {sidebar && toggle("mobile")}
          {sidebar && collapsible && navigationPosition !== "top" && toggle("desktop")}
          {topNav && <div className="maataa-app-shell__topnav">{topNav}</div>}
        </div>
      )}
      <div className="maataa-app-shell__frame" data-position={navigationPosition}>
        {sidebar && (
          <div
            id={navigationId}
            className="maataa-app-shell__navigation"
            data-position={navigationPosition}
            data-open={mobileOpen}
          >
            {navigationContent}
          </div>
        )}
        <div className="maataa-app-shell__content">
          {footer && footerPosition === "above" && (
            <footer className="maataa-app-shell__footer">{footer}</footer>
          )}
          {toolbar && toolbarPosition === "above" && (
            <div className="maataa-app-shell__toolbar">{toolbar}</div>
          )}
          <main id={contentId} className="maataa-app-shell__main" tabIndex={-1}>
            {children}
          </main>
          {toolbar && toolbarPosition === "below" && (
            <div className="maataa-app-shell__toolbar">{toolbar}</div>
          )}
          {footer && footerPosition === "below" && (
            <footer className="maataa-app-shell__footer">{footer}</footer>
          )}
        </div>
      </div>
      {sidebar && (
        <button
          type="button"
          className="maataa-app-shell__backdrop"
          data-open={mobileOpen}
          aria-label="Close navigation"
          tabIndex={mobileOpen ? 0 : -1}
          onClick={() => setMobileOpen(false)}
        />
      )}
    </div>
  );
};

AppShell.displayName = "AppShell";
