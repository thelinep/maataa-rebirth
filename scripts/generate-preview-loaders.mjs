import { readFileSync, writeFileSync } from "node:fs";

const registryPath =
  "src/registries/componentRegistry.ts";

const outputPath =
  "examples/redux-demo/previewLoaders.generated.ts";

/*
 * These exports are already eagerly loaded by the demo App.
 * Giving them another import() edge creates a Vite
 * dynamic/static collision without providing code splitting.
 */
const eagerPreviewExports = new Map([
  ["@maataa/ui/icons/MaataaIcon", "MaataaIcon"],
  ["@maataa/ui/navigation/Tabs", "Tabs"],
  ["@maataa/ui/identity/IdentityAvatar", "IdentityAvatar"],
  ["@maataa/ui/identity/IdentityAvatarGroup", "IdentityAvatarGroup"],
  ["@maataa/ui/identity/IdentityBadge", "IdentityBadge"],
]);

const source =
  readFileSync(registryPath, "utf8");

const importPaths = [
  ...source.matchAll(
    /"importPath"\s*:\s*"(@maataa\/ui\/[^"]+)"/g
  ),
]
  .map((match) => match[1])
  .sort();

const unique = [...new Set(importPaths)];

if (unique.length !== importPaths.length) {
  throw new Error(
    `Duplicate component import paths: ${importPaths.length} records, ${unique.length} unique`
  );
}

const invalid = unique.filter(
  (value) => !value.startsWith("@maataa/ui/")
);

if (invalid.length) {
  throw new Error(
    `Invalid MAATAA import paths:\n${invalid.join("\n")}`
  );
}

for (const path of eagerPreviewExports.keys()) {
  if (!unique.includes(path)) {
    throw new Error(
      `Eager preview exception is not in COMPONENT_REGISTRY: ${path}`
    );
  }
}

const eagerImports = [];
let eagerIndex = 0;

const entries = unique.map((importPath) => {
  const suffix =
    importPath.slice("@maataa/ui/".length);

  const eagerExport =
    eagerPreviewExports.get(importPath);

  if (eagerExport) {
    const alias =
      `__previewEager${eagerIndex++}`;

    eagerImports.push(
      `import { ${eagerExport} as ${alias} } from ${JSON.stringify(
        `../../src/${suffix}`
      )};`
    );

    return (
      `  ${JSON.stringify(importPath)}: ` +
      `async () => ({ ${JSON.stringify(eagerExport)}: ${alias} }),`
    );
  }

  return (
    `  ${JSON.stringify(importPath)}: ` +
    `() => import(${JSON.stringify(
      `../../src/${suffix}.tsx`
    )}),`
  );
});

const output = `// AUTO-GENERATED by scripts/generate-preview-loaders.mjs
// Source of truth: src/registries/componentRegistry.ts
// Do not edit manually.

${eagerImports.join("\n")}

export type PreviewLoader =
  () => Promise<unknown>;

export const PREVIEW_LOADERS:
  Readonly<Record<string, PreviewLoader>> = {
${entries.join("\n")}
};
`;

writeFileSync(outputPath, output);

console.log(
  `Generated ${unique.length} canonical preview loaders`
);

console.log(
  `Eager exceptions: ${eagerPreviewExports.size}`
);

console.log(
  `True dynamic loaders: ${
    unique.length - eagerPreviewExports.size
  }`
);
