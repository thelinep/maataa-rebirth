import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";

const registryPath = "src/registries/componentRegistry.ts";
const outputPath = "examples/redux-demo/previewLoaders.generated.ts";
const groupsPath = "examples/redux-demo/preview-loaders";

/*
 * These exports are already eagerly loaded by the demo App. Keeping them in
 * the small dispatcher avoids Vite's static/dynamic collision warning.
 */
const eagerPreviewExports = new Map([
  ["@maataa/ui/icons/MaataaIcon", "MaataaIcon"],
  ["@maataa/ui/navigation/Tabs", "Tabs"],
  ["@maataa/ui/identity/IdentityAvatar", "IdentityAvatar"],
  ["@maataa/ui/identity/IdentityAvatarGroup", "IdentityAvatarGroup"],
  ["@maataa/ui/identity/IdentityBadge", "IdentityBadge"],
]);

const source = readFileSync(registryPath, "utf8");
const importPaths = [...source.matchAll(/"importPath"\s*:\s*"(@maataa\/ui\/[^"]+)"/g)].map((match) => match[1]);
const unique = [...new Set(importPaths)];

if (unique.length !== importPaths.length) {
  throw new Error(`Duplicate component import paths: ${importPaths.length} records, ${unique.length} unique`);
}

const invalid = unique.filter((value) => !value.startsWith("@maataa/ui/"));
if (invalid.length) throw new Error(`Invalid MAATAA import paths:\n${invalid.join("\n")}`);

for (const path of eagerPreviewExports.keys()) {
  if (!unique.includes(path)) throw new Error(`Eager preview exception is not in COMPONENT_REGISTRY: ${path}`);
}

const byGroup = new Map();
for (const importPath of unique) {
  const suffix = importPath.slice("@maataa/ui/".length);
  const group = suffix.split("/")[0];
  if (!group || group.includes(".")) throw new Error(`Invalid preview group for ${importPath}`);
  if (eagerPreviewExports.has(importPath)) continue;
  const entries = byGroup.get(group) ?? [];
  entries.push({ importPath, suffix });
  byGroup.set(group, entries);
}

rmSync(groupsPath, { recursive: true, force: true });
mkdirSync(groupsPath, { recursive: true });

for (const [group, entries] of byGroup) {
  const loaders = entries.map(({ importPath, suffix }) =>
    `  [${JSON.stringify(importPath)}, () => import(${JSON.stringify(`../../../src/${suffix}.tsx`)})],`
  );
  const output = `// AUTO-GENERATED by scripts/generate-preview-loaders.mjs. Do not edit.\n` +
    `import type { PreviewLoader } from "../previewLoaders.generated";\n\n` +
    `export const PREVIEW_LOADERS: ReadonlyMap<string, PreviewLoader> = new Map<string, PreviewLoader>([\n${loaders.join("\n")}\n]);\n`;
  writeFileSync(`${groupsPath}/${group}.generated.ts`, output);
}

let eagerIndex = 0;
const eagerImports = [];
const eagerEntries = [];
for (const [importPath, exportName] of eagerPreviewExports) {
  const suffix = importPath.slice("@maataa/ui/".length);
  const alias = `__previewEager${eagerIndex++}`;
  eagerImports.push(`import { ${exportName} as ${alias} } from ${JSON.stringify(`../../src/${suffix}`)};`);
  eagerEntries.push(`  [${JSON.stringify(importPath)}, async () => ({ ${JSON.stringify(exportName)}: ${alias} })],`);
}

const groupImports = [...byGroup.keys()].sort().map((group) =>
  `  ${JSON.stringify(group)}: () => import(${JSON.stringify(`./preview-loaders/${group}.generated`)}),`
);

const output = `// AUTO-GENERATED by scripts/generate-preview-loaders.mjs. Do not edit.\n` +
  `${eagerImports.join("\n")}\n\n` +
  `export type PreviewLoader = () => Promise<unknown>;\n\n` +
  `const eagerLoaders: ReadonlyMap<string, PreviewLoader> = new Map<string, PreviewLoader>([\n${eagerEntries.join("\n")}\n]);\n\n` +
  `const previewGroups: Readonly<Record<string, () => Promise<{ PREVIEW_LOADERS: ReadonlyMap<string, PreviewLoader> }>>> = {\n${groupImports.join("\n")}\n};\n\n` +
  `export async function loadPreviewLoader(importPath: string): Promise<PreviewLoader | undefined> {\n` +
  `  const eager = eagerLoaders.get(importPath);\n  if (eager) return eager;\n` +
  `  const group = importPath.slice("@maataa/ui/".length).split("/")[0];\n` +
  `  const loadGroup = previewGroups[group];\n  if (!loadGroup) return undefined;\n` +
  `  return (await loadGroup()).PREVIEW_LOADERS.get(importPath);\n}\n`;

writeFileSync(outputPath, output);
console.log(`Generated ${unique.length} canonical preview loaders across ${byGroup.size} lazy groups`);
