import fs from "node:fs";
import crypto from "node:crypto";
import { readCatalog } from "./read-canonical-catalog.mjs";
const records=readCatalog("src/registries/layoutRegistry.ts","LAYOUT_TYPES");
const shared="src/internal/layoutPreset.tsx";
const sharedSource=fs.readFileSync(shared,"utf8");
const regions=[...sharedSource.matchAll(/\{(\w+) !== undefined && <(Layout\w+)/g)].map(match=>({prop:match[1],atom:match[2]}));
regions.push({prop:"main",atom:"LayoutMain"});
const css=fs.readFileSync("src/styles.css","utf8").split('@media (max-width:900px)')[0];
const entries=records.map(record=>{
  if(!record.importPath.startsWith("@maataa/ui/layouts/"))throw new Error(`Unexpected path ${record.importPath}`);
  const sourcePath=record.importPath.replace("@maataa/ui/","src/")+".tsx";
  const source=fs.readFileSync(sourcePath,"utf8");
  const match=source.match(/<LayoutPreset preset="([^"]+)" template="([^"]+)"/);
  if(!match||!source.includes(`export function ${record.name}(`))throw new Error(`Unproven layout implementation ${record.id}`);
  let areas;
  for(const rule of css.matchAll(/([^{}]+)\{([^{}]+)\}/g)) {
    if(rule[1].includes(`[data-layout-template="${match[2]}"]`)&&!rule[1].includes('>')) {
      const declaration=rule[2].match(/grid-template-areas:([^;]+)/);
      if(declaration)areas=declaration[1];
    }
  }
  const primarySlot=!areas||/\bmain\b/.test(areas)?"main":/\bcanvas\b/.test(areas)?"canvas":/\bdetails\b/.test(areas)?"details":"main";
  return {...record,sourcePath,exportName:record.name,preset:match[1],template:match[2],regions,primarySlot,
    placementStatus:areas?"source-declared":"fallback-main",
    evidence:{kind:"source",reference:sourcePath,sha256:crypto.createHash("sha256").update(source).digest("hex")}};
});
if(new Set(entries.map(x=>x.id)).size!==entries.length)throw new Error("Duplicate layout identities");
const audit={schemaVersion:1,source:"src/registries/layoutRegistry.ts",count:entries.length,
  regionSemantics:"Slots are declared by shared LayoutPreset implementation; application placement compatibility remains unverified.",entries};
const auditPath="docs/engineering/layout-audit.json";
const auditText=JSON.stringify(audit,null,2)+"\n";
if(process.argv.includes("--check")){
  if(fs.readFileSync(auditPath,"utf8")!==auditText)throw new Error("Layout audit stale; regenerate");
}else fs.writeFileSync(auditPath,auditText);
if(!process.argv.includes("--audit-only")){
 const contractFile="src/runtime/layoutContracts.generated.ts";
 const contracts=`// Derived from layout registry, implementation and CSS by generate-layout-loaders.mjs.\nexport const LAYOUT_RUNTIME_CONTRACTS: Readonly<Record<string,{primarySlot:"main"|"canvas"|"details";placementStatus:"source-declared"|"fallback-main";template:string}>> = ${JSON.stringify(Object.fromEntries(entries.map(x=>[x.id,{primarySlot:x.primarySlot,placementStatus:x.placementStatus,template:x.template}])),null,2)};\n`;
 if(process.argv.includes("--check")){if(fs.readFileSync(contractFile,"utf8")!==contracts)throw new Error("Layout contracts stale");}
 else fs.writeFileSync(contractFile,contracts);
 const output=`// Generated by scripts/generate-layout-loaders.mjs from LAYOUT_TYPES. Do not edit.\nimport type { ComponentType } from "react";\nimport type { LayoutPresetProps } from "../internal/layoutPreset";\nexport const CANONICAL_LAYOUT_LOADERS: Readonly<Record<string, () => Promise<{default:ComponentType<LayoutPresetProps>}>>> = {\n${entries.map(entry=>`  ${JSON.stringify(entry.id)}: () => import(${JSON.stringify(entry.importPath.replace("@maataa/ui/","../"))}).then(module => ({default:module.${entry.exportName}})),`).join("\n")}\n};\n`;
 const file="src/runtime/layoutLoaders.generated.ts";
 if(process.argv.includes("--check")){if(fs.readFileSync(file,"utf8")!==output)throw new Error("Layout loaders stale");}
 else fs.writeFileSync(file,output);
}
console.log(`Audited ${entries.length} canonical layouts, ${regions.length} shared declared slots`);
